-- Clean up existing tables (Dependency order reverse)
BEGIN
   FOR c IN (SELECT table_name FROM user_tables WHERE table_name IN (
       'AUDIT_LOG', 'APPEAL_REVIEW', 'APPEAL', 'PAYMENT', 'FINE', 'EVIDENCE',
       'VIOLATION', 'VIOLATION_TYPE', 'VEHICLE_EVENT', 'POLLUTION_CERTIFICATE',
       'VEHICLE_INSURANCE', 'VEHICLE', 'LICENSE', 'DRIVER', 'OWNER',
       'CAMERA_MAINTENANCE', 'CAMERA', 'ROAD_SEGMENT', 'ROAD', 'TRAFFIC_ZONE',
       'CITY', 'OFFICER'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || c.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
EXCEPTION
   WHEN OTHERS THEN NULL;
END;
/

-- 1. CITY Table
CREATE TABLE CITY (
    city_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name       VARCHAR2(100) NOT NULL UNIQUE,
    state_name      VARCHAR2(100) NOT NULL,
    country         VARCHAR2(100) DEFAULT 'India' NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. TRAFFIC_ZONE Table
CREATE TABLE TRAFFIC_ZONE (
    zone_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_code       VARCHAR2(20) NOT NULL UNIQUE,
    zone_name       VARCHAR2(100) NOT NULL,
    city_id         NUMBER NOT NULL,
    risk_level      VARCHAR2(20) DEFAULT 'MEDIUM' CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_zone_city FOREIGN KEY (city_id) REFERENCES CITY(city_id) ON DELETE CASCADE
);

-- 3. ROAD Table
CREATE TABLE ROAD (
    road_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_name       VARCHAR2(150) NOT NULL,
    road_type       VARCHAR2(50) CHECK (road_type IN ('EXPRESSWAY', 'NATIONAL_HIGHWAY', 'ARTERIAL', 'RESIDENTIAL', 'SERVICE')),
    speed_limit_kmh NUMBER(3) NOT NULL CHECK (speed_limit_kmh > 0 AND speed_limit_kmh <= 200),
    zone_id         NUMBER NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_road_zone FOREIGN KEY (zone_id) REFERENCES TRAFFIC_ZONE(zone_id) ON DELETE CASCADE
);

-- 4. ROAD_SEGMENT Table
CREATE TABLE ROAD_SEGMENT (
    segment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_code    VARCHAR2(30) NOT NULL UNIQUE,
    road_id         NUMBER NOT NULL,
    start_latitude  NUMBER(10,7) NOT NULL,
    start_longitude NUMBER(10,7) NOT NULL,
    end_latitude    NUMBER(10,7) NOT NULL,
    end_longitude   NUMBER(10,7) NOT NULL,
    length_km       NUMBER(5,2) CHECK (length_km > 0),
    is_active       NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    CONSTRAINT fk_segment_road FOREIGN KEY (road_id) REFERENCES ROAD(road_id) ON DELETE CASCADE
);

-- 5. CAMERA Table
CREATE TABLE CAMERA (
    camera_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_code     VARCHAR2(50) NOT NULL UNIQUE,
    camera_type     VARCHAR2(30) NOT NULL CHECK (camera_type IN ('ANPR', 'SPEED', 'RED_LIGHT', 'CCTV', 'AI_TRAFFIC')),
    segment_id      NUMBER NOT NULL,
    installation_dt DATE DEFAULT SYSDATE NOT NULL,
    direction       VARCHAR2(20) CHECK (direction IN ('NORTHBOUND', 'SOUTHBOUND', 'EASTBOUND', 'WESTBOUND', 'BI_DIRECTIONAL')),
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'OFFLINE', 'DECOMMISSIONED')),
    ip_address      VARCHAR2(45),
    CONSTRAINT fk_camera_segment FOREIGN KEY (segment_id) REFERENCES ROAD_SEGMENT(segment_id) ON DELETE CASCADE
);

-- 6. CAMERA_MAINTENANCE Table
CREATE TABLE CAMERA_MAINTENANCE (
    maint_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id       NUMBER NOT NULL,
    maintenance_date DATE NOT NULL,
    technician_name VARCHAR2(100) NOT NULL,
    issue_description VARCHAR2(500),
    resolution_details VARCHAR2(500),
    cost            NUMBER(10,2) DEFAULT 0.00 CHECK (cost >= 0),
    CONSTRAINT fk_maint_camera FOREIGN KEY (camera_id) REFERENCES CAMERA(camera_id) ON DELETE CASCADE
);

-- 7. OWNER Table
CREATE TABLE OWNER (
    owner_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    national_id     VARCHAR2(30) NOT NULL UNIQUE,
    full_name       VARCHAR2(150) NOT NULL,
    email           VARCHAR2(100) NOT NULL UNIQUE,
    phone           VARCHAR2(20) NOT NULL,
    address         VARCHAR2(300) NOT NULL,
    owner_type      VARCHAR2(20) DEFAULT 'INDIVIDUAL' CHECK (owner_type IN ('INDIVIDUAL', 'CORPORATE', 'GOVERNMENT')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 8. DRIVER Table
CREATE TABLE DRIVER (
    driver_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        NUMBER, -- Optional mapping if driver is an owner
    full_name       VARCHAR2(150) NOT NULL,
    dob             DATE NOT NULL,
    blood_group     VARCHAR2(5),
    phone           VARCHAR2(20) NOT NULL,
    email           VARCHAR2(100),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_driver_owner FOREIGN KEY (owner_id) REFERENCES OWNER(owner_id) ON DELETE SET NULL
);

-- 9. LICENSE Table
CREATE TABLE LICENSE (
    license_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_number  VARCHAR2(30) NOT NULL UNIQUE,
    driver_id       NUMBER NOT NULL UNIQUE,
    category        VARCHAR2(20) NOT NULL CHECK (category IN ('LMV', 'MCWG', 'HMV', 'TRANS', 'COMMERCIAL')),
    issue_date      DATE NOT NULL,
    expiry_date     DATE NOT NULL,
    demerit_points  NUMBER(3) DEFAULT 0 CHECK (demerit_points >= 0),
    status          VARCHAR2(20) DEFAULT 'VALID' CHECK (status IN ('VALID', 'SUSPENDED', 'EXPIRED', 'REVOKED')),
    CONSTRAINT fk_license_driver FOREIGN KEY (driver_id) REFERENCES DRIVER(driver_id) ON DELETE CASCADE,
    CONSTRAINT chk_license_dates CHECK (expiry_date > issue_date)
);

-- 10. VEHICLE Table (Supertype for Specialization Demonstration)
CREATE TABLE VEHICLE (
    vehicle_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no VARCHAR2(20) NOT NULL UNIQUE,
    owner_id        NUMBER NOT NULL,
    vehicle_class   VARCHAR2(20) NOT NULL CHECK (vehicle_class IN ('PRIVATE', 'COMMERCIAL')),
    make            VARCHAR2(50) NOT NULL,
    model           VARCHAR2(50) NOT NULL,
    fuel_type       VARCHAR2(20) CHECK (fuel_type IN ('PETROL', 'DIESEL', 'ELECTRIC', 'CNG', 'HYBRID')),
    mfg_year        NUMBER(4) CHECK (mfg_year BETWEEN 1900 AND 2100),
    reg_date        DATE DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'STOLEN', 'SCRAPPED', 'BLACKLISTED')),
    CONSTRAINT fk_vehicle_owner FOREIGN KEY (owner_id) REFERENCES OWNER(owner_id) ON DELETE CASCADE
);

-- 11. VEHICLE_INSURANCE Table
CREATE TABLE VEHICLE_INSURANCE (
    insurance_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      NUMBER NOT NULL,
    policy_number   VARCHAR2(50) NOT NULL UNIQUE,
    provider_name   VARCHAR2(100) NOT NULL,
    start_date      DATE NOT NULL,
    end_date        DATE NOT NULL,
    insured_amount  NUMBER(12,2) CHECK (insured_amount >= 0),
    CONSTRAINT fk_ins_vehicle FOREIGN KEY (vehicle_id) REFERENCES VEHICLE(vehicle_id) ON DELETE CASCADE,
    CONSTRAINT chk_ins_dates CHECK (end_date > start_date)
);

-- 12. POLLUTION_CERTIFICATE Table
CREATE TABLE POLLUTION_CERTIFICATE (
    puc_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      NUMBER NOT NULL,
    certificate_no  VARCHAR2(50) NOT NULL UNIQUE,
    issue_date      DATE NOT NULL,
    expiry_date     DATE NOT NULL,
    co2_reading     NUMBER(5,2),
    status          VARCHAR2(20) DEFAULT 'PASS' CHECK (status IN ('PASS', 'FAIL', 'EXPIRED')),
    CONSTRAINT fk_puc_vehicle FOREIGN KEY (vehicle_id) REFERENCES VEHICLE(vehicle_id) ON DELETE CASCADE,
    CONSTRAINT chk_puc_dates CHECK (expiry_date > issue_date)
);

-- 13. VEHICLE_EVENT Table (Raw Camera Observation)
CREATE TABLE VEHICLE_EVENT (
    event_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id       NUMBER NOT NULL,
    vehicle_id      NUMBER, -- Nullable if plate unrecognised
    license_plate_raw VARCHAR2(30),
    event_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    observed_speed  NUMBER(5,2),
    ai_confidence   NUMBER(5,2) CHECK (ai_confidence BETWEEN 0 AND 100),
    event_status    VARCHAR2(20) DEFAULT 'UNPROCESSED' CHECK (event_status IN ('UNPROCESSED', 'FLAGGED', 'CLEARED', 'VIOLATION_CONFIRMED')),
    mongo_doc_id    VARCHAR2(50), -- Cross-reference to MongoDB evidence store
    CONSTRAINT fk_event_camera FOREIGN KEY (camera_id) REFERENCES CAMERA(camera_id) ON DELETE CASCADE,
    CONSTRAINT fk_event_vehicle FOREIGN KEY (vehicle_id) REFERENCES VEHICLE(vehicle_id) ON DELETE SET NULL
);

-- 14. VIOLATION_TYPE Table
CREATE TABLE VIOLATION_TYPE (
    type_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR2(30) NOT NULL UNIQUE,
    title           VARCHAR2(100) NOT NULL,
    description     VARCHAR2(300),
    base_fine       NUMBER(10,2) NOT NULL CHECK (base_fine >= 0),
    demerit_points  NUMBER(2) DEFAULT 0 CHECK (demerit_points >= 0),
    severity        VARCHAR2(20) DEFAULT 'MINOR' CHECK (severity IN ('MINOR', 'MODERATE', 'SEVERE', 'CRITICAL'))
);

-- 15. OFFICER Table
CREATE TABLE OFFICER (
    officer_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    badge_number    VARCHAR2(30) NOT NULL UNIQUE,
    full_name       VARCHAR2(150) NOT NULL,
    rank_title      VARCHAR2(50) NOT NULL,
    zone_id         NUMBER,
    phone           VARCHAR2(20),
    email           VARCHAR2(100) UNIQUE,
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ON_LEAVE', 'RETIRED', 'SUSPENDED')),
    CONSTRAINT fk_officer_zone FOREIGN KEY (zone_id) REFERENCES TRAFFIC_ZONE(zone_id) ON DELETE SET NULL
);

-- 16. VIOLATION Table
CREATE TABLE VIOLATION (
    violation_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        NUMBER UNIQUE,
    vehicle_id      NUMBER NOT NULL,
    driver_id       NUMBER,
    type_id         NUMBER NOT NULL,
    camera_id       NUMBER NOT NULL,
    officer_id      NUMBER, -- Confirming officer if manually reviewed
    violation_dt    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ISSUED' CHECK (status IN ('ISSUED', 'FINE_GENERATED', 'PAID', 'UNDER_APPEAL', 'DISMISSED', 'EXPIRED')),
    remarks         VARCHAR2(500),
    CONSTRAINT fk_viol_event FOREIGN KEY (event_id) REFERENCES VEHICLE_EVENT(event_id) ON DELETE SET NULL,
    CONSTRAINT fk_viol_vehicle FOREIGN KEY (vehicle_id) REFERENCES VEHICLE(vehicle_id) ON DELETE CASCADE,
    CONSTRAINT fk_viol_driver FOREIGN KEY (driver_id) REFERENCES DRIVER(driver_id) ON DELETE SET NULL,
    CONSTRAINT fk_viol_type FOREIGN KEY (type_id) REFERENCES VIOLATION_TYPE(type_id) ON DELETE CASCADE,
    CONSTRAINT fk_viol_camera FOREIGN KEY (camera_id) REFERENCES CAMERA(camera_id) ON DELETE CASCADE,
    CONSTRAINT fk_viol_officer FOREIGN KEY (officer_id) REFERENCES OFFICER(officer_id) ON DELETE SET NULL
);

-- 17. FINE Table
CREATE TABLE FINE (
    fine_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id    NUMBER NOT NULL UNIQUE,
    base_amount     NUMBER(10,2) NOT NULL CHECK (base_amount >= 0),
    penalty_amount  NUMBER(10,2) DEFAULT 0.00 CHECK (penalty_amount >= 0),
    total_amount    NUMBER(10,2) GENERATED ALWAYS AS (base_amount + penalty_amount),
    issue_date      DATE DEFAULT SYSDATE NOT NULL,
    due_date        DATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'UNPAID' CHECK (status IN ('UNPAID', 'PARTIALLY_PAID', 'PAID', 'OVERDUE', 'WAIVED')),
    CONSTRAINT fk_fine_violation FOREIGN KEY (violation_id) REFERENCES VIOLATION(violation_id) ON DELETE CASCADE,
    CONSTRAINT chk_fine_due_date CHECK (due_date >= issue_date)
);

-- 18. PAYMENT Table
CREATE TABLE PAYMENT (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fine_id         NUMBER NOT NULL,
    payment_amount  NUMBER(10,2) NOT NULL CHECK (payment_amount > 0),
    payment_date    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    payment_method  VARCHAR2(30) CHECK (payment_method IN ('CREDIT_CARD', 'DEBIT_CARD', 'UPI', 'NET_BANKING', 'CASH_COUNTER')),
    txn_ref_no      VARCHAR2(100) NOT NULL UNIQUE,
    status          VARCHAR2(20) DEFAULT 'SUCCESS' CHECK (status IN ('SUCCESS', 'PENDING', 'FAILED', 'REFUNDED')),
    CONSTRAINT fk_pay_fine FOREIGN KEY (fine_id) REFERENCES FINE(fine_id) ON DELETE CASCADE
);

-- 19. APPEAL Table
CREATE TABLE APPEAL (
    appeal_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id    NUMBER NOT NULL UNIQUE,
    appellant_id    NUMBER NOT NULL, -- Owner/Driver ID submitting appeal
    appeal_date     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reason          VARCHAR2(1000) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT fk_appeal_violation FOREIGN KEY (violation_id) REFERENCES VIOLATION(violation_id) ON DELETE CASCADE,
    CONSTRAINT fk_appeal_owner FOREIGN KEY (appellant_id) REFERENCES OWNER(owner_id) ON DELETE CASCADE
);

-- 20. APPEAL_REVIEW Table
CREATE TABLE APPEAL_REVIEW (
    review_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appeal_id       NUMBER NOT NULL UNIQUE,
    officer_id      NUMBER NOT NULL,
    review_date     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    decision        VARCHAR2(20) NOT NULL CHECK (decision IN ('APPROVED', 'REJECTED')),
    comments        VARCHAR2(1000) NOT NULL,
    CONSTRAINT fk_rev_appeal FOREIGN KEY (appeal_id) REFERENCES APPEAL(appeal_id) ON DELETE CASCADE,
    CONSTRAINT fk_rev_officer FOREIGN KEY (officer_id) REFERENCES OFFICER(officer_id) ON DELETE CASCADE
);

-- 21. EVIDENCE Table
CREATE TABLE EVIDENCE (
    evidence_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id    NUMBER NOT NULL,
    evidence_type   VARCHAR2(30) CHECK (evidence_type IN ('IMAGE_SNAPSHOT', 'VIDEO_CLIP', 'ANPR_CROP', 'LIDAR_DATA')),
    file_path       VARCHAR2(500) NOT NULL,
    captured_at     TIMESTAMP NOT NULL,
    file_hash_sha256 VARCHAR2(64) NOT NULL,
    confidence_score NUMBER(5,2) CHECK (confidence_score BETWEEN 0 AND 100),
    CONSTRAINT fk_evid_violation FOREIGN KEY (violation_id) REFERENCES VIOLATION(violation_id) ON DELETE CASCADE
);

-- 22. AUDIT_LOG Table
CREATE TABLE AUDIT_LOG (
    log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name     VARCHAR2(50) NOT NULL,
    entity_id       NUMBER NOT NULL,
    action          VARCHAR2(20) NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'STATUS_CHANGE')),
    old_value       VARCHAR2(2000),
    new_value       VARCHAR2(2000),
    performed_by    VARCHAR2(100) DEFAULT USER NOT NULL,
    timestamp       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
