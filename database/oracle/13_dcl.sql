-- 1. Create System Roles
CREATE ROLE ROLE_STVAMS_ADMIN;
CREATE ROLE ROLE_TRAFFIC_OFFICER;
CREATE ROLE ROLE_DATA_ANALYST;
CREATE ROLE ROLE_PAYMENT_OPERATOR;

-- 2. Grant Privileges to ROLE_STVAMS_ADMIN (Full DBA Access to App Schema)
GRANT ALL PRIVILEGES ON CITY TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON TRAFFIC_ZONE TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON ROAD TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON ROAD_SEGMENT TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON CAMERA TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON VEHICLE TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON VIOLATION TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON FINE TO ROLE_STVAMS_ADMIN;
GRANT ALL PRIVILEGES ON PAYMENT TO ROLE_STVAMS_ADMIN;

-- 3. Grant Privileges to ROLE_TRAFFIC_OFFICER (Operational Read/Write on Violations & Appeals)
GRANT SELECT, INSERT, UPDATE ON VIOLATION TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT, INSERT, UPDATE ON APPEAL TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT, INSERT ON APPEAL_REVIEW TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT ON VEHICLE TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT ON DRIVER TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT ON LICENSE TO ROLE_TRAFFIC_OFFICER;
GRANT SELECT ON CAMERA TO ROLE_TRAFFIC_OFFICER;
GRANT EXECUTE ON REGISTER_VIOLATION TO ROLE_TRAFFIC_OFFICER;
GRANT EXECUTE ON REVIEW_APPEAL TO ROLE_TRAFFIC_OFFICER;

-- 4. Grant Privileges to ROLE_DATA_ANALYST (Read-Only Analytical Views & Tables)
GRANT SELECT ON VW_VEHICLE_VIOLATION_SUMMARY TO ROLE_DATA_ANALYST;
GRANT SELECT ON VW_PENDING_FINES TO ROLE_DATA_ANALYST;
GRANT SELECT ON VW_CAMERA_PERFORMANCE TO ROLE_DATA_ANALYST;
GRANT SELECT ON VW_TRAFFIC_HOTSPOTS TO ROLE_DATA_ANALYST;
GRANT SELECT ON VW_OFFICER_CASES TO ROLE_DATA_ANALYST;

-- 5. Grant Privileges to ROLE_PAYMENT_OPERATOR (Payment Entry & Fine Inspection)
GRANT SELECT ON FINE TO ROLE_PAYMENT_OPERATOR;
GRANT SELECT, INSERT ON PAYMENT TO ROLE_PAYMENT_OPERATOR;
GRANT EXECUTE ON PROCESS_PAYMENT TO ROLE_PAYMENT_OPERATOR;

-- 6. Demonstration of REVOKE
REVOKE INSERT ON FINE FROM ROLE_PAYMENT_OPERATOR;
