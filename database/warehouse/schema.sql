-- 1. DIM_DATE Dimension
CREATE TABLE DIM_DATE (
    date_key        NUMBER(8) PRIMARY KEY, -- YYYYMMDD
    full_date       DATE NOT NULL,
    day_of_week     VARCHAR2(15) NOT NULL,
    day_of_month    NUMBER(2) NOT NULL,
    month_name      VARCHAR2(15) NOT NULL,
    quarter         VARCHAR2(2) NOT NULL,
    year            NUMBER(4) NOT NULL,
    is_weekend      NUMBER(1) CHECK (is_weekend IN (0, 1))
);

-- 2. DIM_TIME Dimension
CREATE TABLE DIM_TIME (
    time_key        NUMBER(6) PRIMARY KEY, -- HHMMSS
    hour_24         NUMBER(2) NOT NULL,
    minute          NUMBER(2) NOT NULL,
    time_of_day     VARCHAR2(20) CHECK (time_of_day IN ('MORNING_PEAK', 'EVENING_PEAK', 'DAY_NORMAL', 'NIGHT'))
);

-- 3. DIM_VEHICLE Dimension (SCD Type 2 Capable)
CREATE TABLE DIM_VEHICLE (
    vehicle_sk      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      NUMBER NOT NULL,
    registration_no VARCHAR2(20) NOT NULL,
    vehicle_class   VARCHAR2(20) NOT NULL,
    make            VARCHAR2(50),
    model           VARCHAR2(50),
    fuel_type       VARCHAR2(20),
    owner_type      VARCHAR2(20)
);

-- 4. DIM_CAMERA Dimension
CREATE TABLE DIM_CAMERA (
    camera_sk       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id       NUMBER NOT NULL,
    camera_code     VARCHAR2(50) NOT NULL,
    camera_type     VARCHAR2(30) NOT NULL,
    direction       VARCHAR2(20)
);

-- 5. DIM_ZONE Dimension
CREATE TABLE DIM_ZONE (
    zone_sk         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id         NUMBER NOT NULL,
    zone_code       VARCHAR2(20) NOT NULL,
    zone_name       VARCHAR2(100) NOT NULL,
    city_name       VARCHAR2(100) NOT NULL,
    risk_level      VARCHAR2(20) NOT NULL
);

-- 6. DIM_VIOLATION_TYPE Dimension
CREATE TABLE DIM_VIOLATION_TYPE (
    type_sk         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id         NUMBER NOT NULL,
    code            VARCHAR2(30) NOT NULL,
    title           VARCHAR2(100) NOT NULL,
    severity        VARCHAR2(20) NOT NULL
);

-- 7. FACT_VIOLATION (Central Violation Fact Table)
CREATE TABLE FACT_VIOLATION (
    fact_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key        NUMBER(8) REFERENCES DIM_DATE(date_key),
    time_key        NUMBER(6) REFERENCES DIM_TIME(time_key),
    vehicle_sk      NUMBER REFERENCES DIM_VEHICLE(vehicle_sk),
    camera_sk       NUMBER REFERENCES DIM_CAMERA(camera_sk),
    zone_sk         NUMBER REFERENCES DIM_ZONE(zone_sk),
    type_sk         NUMBER REFERENCES DIM_VIOLATION_TYPE(type_sk),
    -- Measures
    violation_count NUMBER DEFAULT 1 NOT NULL,
    base_fine_amt   NUMBER(10,2) NOT NULL,
    penalty_amt     NUMBER(10,2) DEFAULT 0.00,
    total_fine_amt  NUMBER(10,2) NOT NULL,
    observed_speed  NUMBER(5,2)
);

-- 8. FACT_PAYMENT (Revenue Fact Table)
CREATE TABLE FACT_PAYMENT (
    payment_fact_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key        NUMBER(8) REFERENCES DIM_DATE(date_key),
    zone_sk         NUMBER REFERENCES DIM_ZONE(zone_sk),
    type_sk         NUMBER REFERENCES DIM_VIOLATION_TYPE(type_sk),
    -- Measures
    payment_count   NUMBER DEFAULT 1 NOT NULL,
    amount_collected NUMBER(12,2) NOT NULL
);
